// E5 taxonomy: T1 oracle (engine number vs an independent number)
// INDEPENDENT reference cross-checks for the bond kernels — validating penny-perfection against
// references OTHER than QuantLib, and QuantLib-FREE (so this runs in the engine's own gate binary):
//
//   1. Excel / OpenFormula PRICE & YIELD (basis 1 = Actual/Actual) — the spreadsheet street convention,
//      reimplemented here from its published formula (a different algebra than our Horner kernel). Matching
//      it catches implementation bugs a single oracle could hide.
//   2. 31 CFR Part 356 Appendix B — the OFFICIAL US Treasury price/yield formula, including the SHORT
//      first-coupon (when-issued) case, reimplemented from the regulation. NB App B is a DIFFERENT
//      convention from what our kernel implements — see the note below — so this test pins the exact,
//      understood relationship between the two, not equality.
//   3. A REQUIRED golden CSV (tests/golden/bond_reference.csv) generated by an external, non-QuantLib library:
//      OpenGamma Strata 2.12.56 (Apache-2.0) US_STREET, via tools/bond_reference/gen_golden.py (jars pinned by
//      SHA-256). A missing file FAILS (P9). Until 2026-09-14 it came from Rateslib (non-commercial licence, LIC1).
//
// ===================================================================================================
// STREET vs TREASURY (31 CFR App B) DISCOUNTING — the one convention difference, stated once.
// ===================================================================================================
// Both conventions agree on the cashflows, on accrued, and on the whole coupon polynomial
// Q(v) = Σ CF_k·v^k. They differ ONLY in how the FRACTIONAL first period w is discounted:
//
//   STREET (ours, QuantLib BondFunctions/Compounded, Rateslib "us_gb"):   dirty = Q(v) · v^w
//   TREASURY, 31 CFR Part 356 App B (Rateslib "ust_31bii"/"us_gb_tsy"):   dirty = Q(v) / (1 + w·y/f)
//
// The regulation is uniform on this: every sub-case in App B Section II (regular first period, short
// first, long first, and the three reopened cases) is written "P[1 + (r/s)(i/2)] = ..." — SIMPLE
// interest over r/s, never a compound (1+i/2)^(r/s). So
//
//   dirty_AppB = dirty_street · (1 + y/f)^w / (1 + w·y/f)
//
// which is an exact identity, not an approximation. On a 6y note at y=2% (w = 30/184) it is ~7e-6 of
// price — ~0.7 bp — so the two are NOT interchangeable at the tolerances this repo works to.
//
// THE KERNEL NOW IMPLEMENTS BOTH, selected by pricing::YieldConvention (see the table in
// pricing/bond.hpp). `build::us_treasury` is STREET (compound stub, simple once only the final coupon
// remains); `build::us_treasury_tsy` is the App B / Treasury method (simple stub always); the plain
// `fixed_rate_bond` default is compound-everywhere, i.e. the UK gilt / French OAT mode. The WI builders
// mirror the same pair. Both have QuantLib oracles -- Compounded and SimpleThenCompounded respectively.
//
// See docs/bond-pricing.md §"Cross-validation beyond QuantLib".

