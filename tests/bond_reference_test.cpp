// INDEPENDENT reference cross-checks for the bond kernels — validating penny-perfection against
// references OTHER than QuantLib, and QuantLib-FREE (so this runs in the engine's own gate binary):
//
//   1. Excel / OpenFormula PRICE & YIELD (basis 1 = Actual/Actual) — the spreadsheet street convention,
//      reimplemented here from its published formula (a different algebra than our Horner kernel). Matching
//      it catches implementation bugs a single oracle could hide.
//   2. 31 CFR Part 356 Appendix B — the OFFICIAL US Treasury price/yield formula, including the SHORT
//      first-coupon (when-issued) case, reimplemented from the regulation.
//   3. An OPTIONAL golden CSV (tests/golden/bond_reference.csv) generated by an external library
//      (Rateslib `calc_mode="ust_31bii"`/`us_gb`, or Bloomberg) via tools/bond_reference/gen_golden.py.
//      Skipped (GTEST_SKIP) if the file is absent, so the gate is green without the external tool but
//      pins the numbers exactly when it is present.
//
// See docs/bond-pricing.md §"Cross-validation beyond QuantLib".

#include <gtest/gtest.h>

#include <cmath>
#include <fstream>
#include <sstream>
#include <string>
